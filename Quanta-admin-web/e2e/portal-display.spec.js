test('长文章目录只滚动文档、不裁切正文，手动阅读同步高亮并隔离目录滚轮', async ({ page, api }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  api.forumPost.content = Array.from({ length: 36 }, (_, index) => `## 第${index + 1}节\n\n${('这是一段用于验证长文章目录定位的正文。'.repeat(12) + '\n\n').repeat(3)}`).join('\n\n')
  await loginAs(page, 'member')
  await page.goto('/member/community/1')
  const toc = page.getByRole('complementary', { name: '文章目录' })
  const article = page.locator('.community-detail__post')
  const heading = page.locator('.community-markdown h2').nth(17)
  const link = toc.getByRole('link', { name: '第18节', exact: true })
  await expect(toc).toBeVisible()
  await link.click()
  const highlights = await page.evaluate(() => new Promise(resolve => {
    const labels = []
    function sample() {
      labels.push(document.querySelector('.community-toc [aria-current]')?.textContent)
      if (labels.length < 30) requestAnimationFrame(sample)
      else resolve(labels)
    }
    sample()
  }))
  expect(highlights.every(label => label === '第18节')).toBe(true)
  await expect.poll(() => heading.evaluate(el => Math.round(el.getBoundingClientRect().top)), { timeout: 5000 }).toBeGreaterThanOrEqual(90)
  await expect.poll(() => heading.evaluate(el => Math.round(el.getBoundingClientRect().top)), { timeout: 5000 }).toBeLessThanOrEqual(100)
  expect(await article.evaluate(el => el.scrollTop)).toBe(0)
  await expect(link).toHaveAttribute('aria-current', 'location')
  await expect(toc.locator('nav')).toHaveCSS('overscroll-behavior-y', 'contain')
  await page.screenshot({ path: testInfo.outputPath('article-toc-position.png') })
  const next = page.locator('.community-markdown h2').nth(31)
  await page.evaluate(el => scrollTo({ top: scrollY + el.getBoundingClientRect().top - 96, behavior: 'instant' }), await next.elementHandle())
  await expect(toc.getByRole('link', { name: '第32节', exact: true })).toHaveAttribute('aria-current', 'location')
  const activeBox = await toc.getByRole('link', { name: '第32节', exact: true }).boundingBox(), navBox = await toc.locator('nav').boundingBox()
  expect(activeBox.y).toBeGreaterThanOrEqual(navBox.y - 1)
  expect(activeBox.y + activeBox.height).toBeLessThanOrEqual(navBox.y + navBox.height + 1)
  expect(new URL(page.url()).hash).toBe('')
})

test('后台折叠菜单图标居中，手机复用展开收起图标且不改变桌面按钮', async ({ page, api }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await loginAs(page, 'admin')
  const desktop = page.locator('.app-header__toggle')
  const foldIcon = await desktop.locator('svg').innerHTML()
  await desktop.click()
  const expandIcon = await desktop.locator('svg').innerHTML()
  await expect(page.locator('.app-sidebar')).toHaveCSS('width', '76px')
  const sidebar = await page.locator('.app-sidebar').boundingBox()
  for (const icon of await page.locator('.app-sidebar__menu .el-menu-item .el-icon').all()) {
    const box = await icon.boundingBox()
    expect(Math.abs(box.x + box.width / 2 - sidebar.x - sidebar.width / 2)).toBeLessThan(1)
  }
  await expect(page.locator('.el-message')).toHaveCount(0)
  await expect(page.locator('#nprogress')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('admin-collapsed-aligned.png') })
  await page.setViewportSize({ width: 390, height: 900 })
  const mobile = page.locator('.app-header__mobile-toggle')
  await expect(mobile).toBeVisible()
  expect(await mobile.locator('svg').innerHTML()).toBe(expandIcon)
  await page.screenshot({ path: testInfo.outputPath('admin-mobile-expand.png') })
  await mobile.click()
  await expect(page.locator('.app-sidebar')).toHaveAttribute('aria-hidden', 'false')
  expect(await mobile.locator('svg').innerHTML()).toBe(foldIcon)
  await page.keyboard.press('Escape')
  await expect(page.locator('.app-sidebar')).toHaveAttribute('aria-hidden', 'true')
  expect(api.requests).toContain('GET /getRouters')
})
