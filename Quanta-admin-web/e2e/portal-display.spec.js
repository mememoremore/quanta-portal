for (const width of [320, 390, 768, 1440]) {
  test(`门户 ${width}px 头像外框、箭头对齐和首页融合Logo`, async ({ page, api }, testInfo) => {
    await page.setViewportSize({ width, height: 940 })
    await loginAs(page, 'member')
    await expect(page.locator('.member-home__hero h1')).toContainText('塔员同学')
    await expect(page.locator('#nprogress')).toHaveCount(0)
    await expect(page.locator('.el-message')).toHaveCount(0)
    const trigger = page.locator('.portal-user-menu__trigger')
    const watermark = page.locator('.member-home__brand-mark')
    await expect(watermark).toBeVisible()
    await expect(watermark).toHaveAttribute('aria-hidden', 'true')
    await expect(watermark).toHaveCSS('pointer-events', 'none')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width <= 760) {
      await expect(trigger).toHaveCSS('border-top-width', '0px')
      await expect(trigger).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
      expect((await trigger.boundingBox()).width).toBeGreaterThanOrEqual(44)
    } else {
      await expect(trigger).toHaveCSS('border-top-width', '1px')
      const arrow = page.locator('.portal-user-menu__chevron svg')
      await expect(arrow).toBeVisible()
      const arrowBox = await arrow.boundingBox(), triggerBox = await trigger.boundingBox()
      expect(Math.abs(arrowBox.y + arrowBox.height / 2 - triggerBox.y - triggerBox.height / 2)).toBeLessThan(1)
    }
    const markBox = await watermark.boundingBox(), avatar = await page.locator('.member-home__profile-link').boundingBox()
    if (width <= 520) expect(markBox.x).toBeGreaterThan(avatar.x + avatar.width)
    else expect(markBox.x + markBox.width).toBeLessThan(avatar.x)
    await page.screenshot({ path: testInfo.outputPath(`member-home-${width}.png`) })
    await trigger.click()
    await expect(page.getByRole('menu')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('menu')).toHaveCount(0)
    await page.getByRole('link', { name: '进入个人中心', exact: true }).click()
    await expect(page).toHaveURL(/\/member\/profile$/)
    expect(api.requests).toContain('GET /getInfo')
  })
}

