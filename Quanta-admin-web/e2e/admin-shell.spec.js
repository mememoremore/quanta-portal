import { test, expect, loginAs } from './support/fixture.js'

test('后台侧栏职位显示中文，普通菜单无尾部箭头，退出登录仍正常', async ({ page, api }) => {
  await loginAs(page, 'viewer')
  await expect(page.locator('.user-panel__copy small')).toHaveText('产品部 · 经理')
  const member = page.locator('.app-sidebar .el-menu-item').filter({ hasText: '控制台' })
  await expect(member.locator('svg')).toHaveCount(1)
  await page.locator('.user-panel').click()
  await page.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/admin\/login$/)
  expect(api.requests).toContain('POST /logout')
})

test('后台手机抽屉保持窄宽度，选择菜单后关闭，切回桌面可折叠', async ({ page, api }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await loginAs(page, 'admin')
  await page.getByRole('button', { name: '打开导航菜单', exact: true }).click()
  const sidebar = page.locator('.app-sidebar')
  await expect(sidebar).toHaveAttribute('aria-hidden', 'false')
  await expect(sidebar).toHaveCSS('width', '224px')
  await expect.poll(async () => Math.abs((await sidebar.boundingBox()).x)).toBeLessThan(1)
  await expect(page.locator('.app-layout__backdrop')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('admin-drawer-h5.png') })
  await sidebar.getByRole('menuitem', { name: '学习资料', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/learning-materials$/)
  await expect(sidebar).toHaveAttribute('aria-hidden', 'true')
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(sidebar).toHaveAttribute('aria-hidden', 'false')
  await page.getByRole('button', { name: '折叠侧边栏', exact: true }).click()
  await expect(sidebar).toHaveCSS('width', '76px')
  await page.getByRole('button', { name: '展开侧边栏', exact: true }).click()
  await expect(sidebar).toHaveCSS('width', '210px')
  await sidebar.getByRole('menuitem', { name: '控制台', exact: true }).click()
  await expect(page.locator('.welcome-banner__mark')).toBeVisible()
  await expect(page.locator('#nprogress')).toHaveCount(0)
  await expect(page.locator('.el-message')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('admin-dashboard-desktop.png') })
  expect(api.requests).toContain('GET /qt/materials')
})
