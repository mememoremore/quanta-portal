import { test, expect, loginAs } from './support/fixture.js'

const yaml = 'on:\n  push:\n    branches: [main]\npermissions:\n  contents: read\n'
const body = `## CI 配置说明\n\n这是一个技术帖子。\n\n\`\`\`yaml\n${yaml}\`\`\`\n`

for (const width of [390, 1440]) {
  test(`论坛 ${width}px 选择器样式、草稿恢复及发布流程正常`, async ({ page, api }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await loginAs(page, 'member')
    await page.goto('/member/community/new')
    const category = page.locator('.community-category-select')
    const selectorHeight = await category.locator('.el-select__wrapper').evaluate((element) => element.getBoundingClientRect().height)
    expect(selectorHeight).toBeGreaterThanOrEqual(50)
    expect(selectorHeight).toBeLessThanOrEqual(60)
    const inputHeight = await category.getByRole('combobox').evaluate((element) => element.getBoundingClientRect().height)
    expect(inputHeight).toBeLessThan(40)
    await category.locator('.el-select__wrapper').click()
    const option = page.getByRole('option', { name: '技术分享', exact: true })
    await expect(option).toBeVisible()
    expect(await option.evaluate((element) => getComputedStyle(element).listStyleType)).toBe('none')
    await page.screenshot({ path: testInfo.outputPath(`editor-category-${width}.png`), animations: 'disabled' })
    await option.click()
    await page.getByPlaceholder('给讨论起个清晰的标题').fill('YAML 技术分享')
    await page.getByRole('textbox', { name: '帖子正文' }).fill(body)
    await expect(page.getByRole('status')).toContainText('草稿已保存到此设备')
    await page.reload()
    await expect(page.getByPlaceholder('给讨论起个清晰的标题')).toHaveValue('YAML 技术分享')
    await expect(page.getByRole('textbox', { name: '帖子正文' })).toHaveValue(body)
    await expect(category).toContainText('技术分享')

    api.forumPublishFailure = true
    await page.getByRole('button', { name: '发布帖子', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('模拟发布失败')
    await expect(page.getByRole('textbox', { name: '帖子正文' })).toHaveValue(body)
    api.forumPublishFailure = false
    await page.getByRole('button', { name: '发布帖子', exact: true }).click()
    await expect(page).toHaveURL(/\/member\/community\/2$/)
    await expect(page.getByRole('heading', { name: 'YAML 技术分享', exact: true })).toBeVisible()
    expect(await page.evaluate(() => localStorage.getItem('quanta:forum-draft:v1:102:new'))).toBeNull()
    await expect(page.locator('code.language-yaml .hljs-attr').first()).toBeVisible()
    await expect(page.getByText('23 次浏览')).toBeVisible()
    const author = page.locator('.community-detail__author')
    const article = page.locator('.community-detail__post')
    expect(await author.evaluate((element) => getComputedStyle(element).display)).toBe(width === 390 ? 'grid' : 'flex')
    expect(await article.evaluate((element) => getComputedStyle(element).paddingLeft)).toBe(width === 390 ? '0px' : '30px')
    expect(await article.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe(width === 390 ? '0px' : '1px')
    const copyButton = page.getByRole('button', { name: '复制代码', exact: true })
    if (width === 390) {
      await expect(copyButton).toBeVisible()
      await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
      await copyButton.click()
      expect((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n')).toBe(yaml)
      await expect(page.locator('.el-message')).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath('post-h5.png') })
      await page.setViewportSize({ width: 320, height: 800 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
    } else {
      await expect(copyButton).toBeHidden()
      await expect(page.locator('.el-message')).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath('post-desktop.png') })
    }
  })
}

test('手机侧边抽屉支持关闭和导航，切回桌面后保留原导航', async ({ page, api }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await loginAs(page, 'member')
  await page.goto('/member/community')
  const toggle = page.getByTestId('portal-mobile-menu')
  await toggle.click()
  const drawer = page.getByRole('dialog', { name: '塔员门户导航' })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByRole('link', { name: '社区论坛', exact: true })).toBeVisible()
  await expect(page.getByTestId('portal-desktop-nav')).toBeHidden()
  await expect.poll(async () => Math.round((await drawer.boundingBox()).x)).toBe(110)
  expect(Math.round((await drawer.boundingBox()).width)).toBe(280)
  await page.screenshot({ path: testInfo.outputPath('portal-drawer-h5.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 844 })
  await expect.poll(async () => Math.round((await drawer.boundingBox()).width)).toBe(264)
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(toggle).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await toggle.click()
  await drawer.getByRole('link', { name: '社区论坛', exact: true }).click()
  await expect(drawer).toBeHidden()
  await page.getByRole('tab', { name: /我发布的/ }).click()
  await expect(page.getByRole('tab', { name: /我发布的/ })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: /我发布的/ }).click()
  await expect(page.getByRole('tab', { name: /我发布的/ })).toHaveAttribute('aria-selected', 'false')
  await toggle.click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(drawer).toBeHidden()
  await expect(page.getByTestId('portal-desktop-nav')).toBeVisible()
  await expect(toggle).toBeHidden()
  expect(api.requests).toContain('GET /qt/forum/posts')
})

test('编辑已有帖子草稿和新帖草稿分开保存，刷新后均可恢复', async ({ page, api }) => {
  await loginAs(page, 'member')
  await page.goto('/member/community/new')
  await page.getByPlaceholder('给讨论起个清晰的标题').fill('新帖草稿')
  await page.getByRole('textbox', { name: '帖子正文' }).fill('新帖还没写完')
  await page.goto('/member/community/1/edit')
  await expect(page.getByPlaceholder('给讨论起个清晰的标题')).toHaveValue(api.forumPost.title)
  await page.getByRole('textbox', { name: '帖子正文' }).fill('已有帖子的未提交修改')
  await expect(page.getByRole('status')).toContainText('草稿已保存到此设备')
  await page.reload()
  await expect(page.getByRole('textbox', { name: '帖子正文' })).toHaveValue('已有帖子的未提交修改')
  await page.goto('/member/community/new')
  await expect(page.getByPlaceholder('给讨论起个清晰的标题')).toHaveValue('新帖草稿')
  await expect(page.getByRole('textbox', { name: '帖子正文' })).toHaveValue('新帖还没写完')
  expect(api.requests).not.toContain('POST /qt/forum/posts')
  expect(api.requests).not.toContain('PUT /qt/forum/posts/1')
})
